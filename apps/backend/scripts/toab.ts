import { spawn, type ChildProcess } from "node:child_process";
import { unwatchFile, watchFile } from "node:fs";
import { glob, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { rolldown, watch, type InputOptions, type OutputOptions } from "rolldown";
import type { FastifyToabConfigOptions } from "../src/toab/index.js";

// Loaded from node_modules at runtime instead of being bundled: Fastify and its
// plugins (swagger-ui serves files from its package directory) and Pino, whose
// transport workers resolve their files relative to the package.
const external = [
  "fastify",
  "@fastify/cors",
  "@fastify/helmet",
  "@fastify/multipart",
  "@fastify/swagger",
  "@fastify/swagger-ui",
  "@fastify/under-pressure",
  "pino",
  "pino-pretty",
];

const cwd = process.cwd();
const configFile = path.join(cwd, "fastify-toab.config.ts");
const envFile = path.join(cwd, ".env");

type BuildConfig = {
  rootDir: string;
  workDir: string;
  rolldown: FastifyToabConfigOptions["rolldown"];
};

async function loadConfig(): Promise<BuildConfig> {
  const { default: config } = (await import(pathToFileURL(configFile).href)) as {
    default: FastifyToabConfigOptions;
  };
  const rootDir = config.rootDir ?? "src";
  return { rootDir, workDir: path.join(cwd, rootDir), rolldown: config.rolldown };
}

async function find(pattern: string, dir: string) {
  const files: string[] = [];
  for await (const file of glob(pattern, { cwd: dir })) files.push(file.split(path.sep).join("/"));
  return files.sort();
}

const capitalize = (word: string) => word.charAt(0).toUpperCase() + word.slice(1);
const importPath = (file: string) => `../${file.replace(/\.ts$/, ".js")}`;
// altcha/altcha.service.ts -> altcha_altcha$service
const importId = (file: string) => file.replace(/\.ts$/, "").split("/").join("_").split(".").join("$");

function internalsTemplate(services: string[]) {
  const names = services.map((file) => path.posix.basename(file, ".service.ts"));
  return `/*
AUTOGENERATED by scripts/toab.ts
*/

import type { InferService, ServiceContainer } from "../toab/index.js";

${services.map((file, i) => `import ${names[i]}Service from "${importPath(file)}";`).join("\n")}

${names.map((name) => `export type ${capitalize(name)}Service = InferService<typeof ${name}Service>;`).join("\n")}

${names.map((name) => `export function get${capitalize(name)}Service(deps: ServiceContainer) {
  return deps.get<${capitalize(name)}Service>(${name}Service.name);
}`).join("\n")}
`;
}

function registriesTemplate(services: string[], controllers: string[]) {
  return `/*
AUTOGENERATED by scripts/toab.ts
*/

import { ControllerRegistry, ServiceRegistry, type Registries } from "../toab/index.js";
${[...services, ...controllers].map((file) => `import ${importId(file)} from "${importPath(file)}";`).join("\n")}

let registries: Registries | null = null;

export async function getRegistries(): Promise<Registries> {
  if (registries !== null) return registries;

  const serviceRegistry = new ServiceRegistry();
${services.map((file) => `  serviceRegistry.register(${importId(file)});`).join("\n")}

  const controllerRegistry = new ControllerRegistry(serviceRegistry);
${controllers.map((file) => `  controllerRegistry.register(${importId(file)});`).join("\n")}

  registries = { serviceRegistry, controllerRegistry };
  return registries;
}
`;
}

const runTemplate = `/*
AUTOGENERATED by scripts/toab.ts
*/

import "dotenv/config";
import { startServer } from "../toab/index.js";

import config from "../../fastify-toab.config.js";
import { getRegistries } from "./registries.js";
import instrumentationFn from "../instrumentation.js";

startServer(getRegistries, instrumentationFn, config).catch((err) => {
  console.error(err);
  process.exit(1);
});
`;

async function rebuild(config: BuildConfig) {
  const services = await find("**/*.service.ts", config.workDir);
  const controllers = await find("**/*.controller.ts", config.workDir);
  const internals = path.join(config.workDir, "@internals");
  await mkdir(internals, { recursive: true });
  await writeFile(path.join(internals, "index.ts"), internalsTemplate(services));
  await writeFile(path.join(internals, "registries.ts"), registriesTemplate(services, controllers));
  await writeFile(path.join(internals, "run.ts"), runTemplate);
}

function bundleOptions(config: BuildConfig, outDir: string, onBuildDone?: () => void) {
  const { inputObject, plugins, external: configExternal, output, ...rest } = config.rolldown ?? {};
  const input = {
    ...rest,
    input: { "@internals/run": path.join(config.rootDir, "@internals/run.ts"), ...inputObject },
    platform: "node",
    plugins: [
      ...(plugins ?? []),
      ...(onBuildDone ? [{ name: "on-build-done", writeBundle: onBuildDone }] : []),
    ],
    external: [...(configExternal ?? []), ...external],
    onLog(level, log, defaultHandler) {
      // A dependency that cannot be resolved would otherwise be left as a bare
      // import and only fail when the image starts.
      if (log.code === "UNRESOLVED_IMPORT") defaultHandler("error", log);
      else defaultHandler(level, log);
    },
  } satisfies InputOptions;
  const outputOptions = {
    ...output,
    dir: outDir,
    format: "esm",
    cleanDir: true,
    minify: true,
    sourcemap: true,
    strict: true,
    esModule: true,
    preserveModules: false,
    banner: `import { fileURLToPath as __fileURLToPath } from 'node:url';
import { dirname as __dirnameFn } from 'node:path';
const __filename = __fileURLToPath(import.meta.url);
const __dirname = __dirnameFn(__filename);`,
  } satisfies OutputOptions;
  return { input, output: outputOptions };
}

async function build(config: BuildConfig) {
  const { input, output } = bundleOptions(config, ".build");
  const bundle = await rolldown(input);
  try {
    await bundle.write(output);
  } finally {
    await bundle.close();
  }
  console.log("Built .build/@internals/run.js");
}

async function dev(config: BuildConfig) {
  let server: ChildProcess | null = null;
  let startedOnce = false;

  async function restart() {
    console.log(`Build complete, ${startedOnce ? "re" : ""}starting server...`);
    startedOnce = true;
    const previous = server;
    if (previous && previous.exitCode === null) {
      await new Promise<void>((resolve) => {
        previous.once("exit", () => resolve());
        previous.kill("SIGKILL");
      });
    }
    const child = spawn("node", [path.join(".dev", "@internals", "run.js")], {
      stdio: "inherit",
      env: { ...process.env, NODE_ENV: "development", NODE_OPTIONS: "--enable-source-maps" },
    });
    child.on("exit", () => { if (server === child) server = null; });
    child.on("error", (error) => {
      console.error("Failed to start server process:", error);
      if (server === child) server = null;
    });
    server = child;
  }

  for (const file of [envFile, configFile]) {
    watchFile(file, { interval: 300 }, () => {
      // Also called once for a missing .env; the first build starts the server.
      if (!startedOnce) return;
      console.log(`${path.basename(file)} changed, reloading server...`);
      void restart();
    });
  }
  process.on("exit", () => {
    unwatchFile(envFile);
    unwatchFile(configFile);
  });

  const { input, output } = bundleOptions(config, ".dev", () => void restart());
  const watcher = watch({ ...input, output });
  await new Promise<void>((resolve, reject) => {
    watcher.on("event", async (event) => {
      switch (event.code) {
        case "BUNDLE_END":
          return await event.result.close();
        case "END":
          return resolve();
        case "ERROR":
          return reject(event.error);
      }
    });
  });
}

const commands: Record<string, (config: BuildConfig) => Promise<void>> = { rebuild, build, dev };
const command = commands[process.argv[2] ?? ""];
if (!command) {
  console.error("Usage: tsx scripts/toab.ts rebuild|build|dev");
  process.exit(2);
}
await command(await loadConfig());
